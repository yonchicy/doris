INSERT INTO qc_list_dt1_dt2_rolling
SELECT
    n.number + copies.number * 2073600,
    seconds_add(CAST('2026-08-16 00:00:00' AS DATETIMEV2(0)), n.h1 * 3600 + n.s),
    seconds_add(CAST('2026-08-17 00:00:00' AS DATETIMEV2(0)), n.h2 * 3600 + (n.s * 37) % 3600),
    (n.h1 + 1) * 1000000 + (n.h2 + 1) * 10000 + n.s + 1
FROM (
    SELECT number,
           CAST(FLOOR(number / 86400) AS INT) AS h1,
           CAST(FLOOR(number / 3600) AS INT) % 24 AS h2,
           CAST(number % 3600 AS INT) AS s
    FROM numbers("number" = "2073600")
) n
CROSS JOIN numbers("number" = "1") copies; -- 造数倍率 R，仅改这里

-- 完整性检查，默认 R=1：2073600 / 26182933516800 / 86400 / 86400，
-- dt1 最早/最晚为 2026-08-16 00:00:00 / 23:59:59；dt2 对应 2026-08-17。
SELECT /* QC2D_FULL_COVERAGE */ COUNT(*) AS row_count, SUM(col1) AS sum_col1,
       COUNT(DISTINCT dt1) AS dt1_seconds, COUNT(DISTINCT dt2) AS dt2_seconds,
       CAST(MIN(dt1) AS STRING) AS dt1_min, CAST(MAX(dt1) AS STRING) AS dt1_max,
       CAST(MIN(dt2) AS STRING) AS dt2_min, CAST(MAX(dt2) AS STRING) AS dt2_max
FROM qc_list_dt1_dt2_rolling;

