-- 双时间列全天连续数据：按小时 LIST 表达式分区的 8 小时滚动窗口
--
-- dt1：2026-08-16 00:00:00～23:59:59；dt2：2026-08-17 00:00:00～23:59:59。
-- 表按 date_trunc(dt1, 'hour')、date_trunc(dt2, 'hour') 分区，明确不是按天分区。
-- 两列小时取 24×24 的完整组合，形成 576 个分区，每分区 1 bucket、1 副本。
-- 每小时组合含 3600 行；两列都覆盖该小时全部秒值，默认共 2,073,600 行。
-- 两列秒偏移采用 s 与 (s*37)%3600 的一一置换，避免始终同步。
-- 每列有连续 86400 个时间值，各时间值出现 24 次；两列的小时是笛卡尔积。
--
-- A：dt1 的 08-16 [12:00,20:00)，dt2 的 08-17 [12:00,20:00)。
-- D：dt1 的 08-16 [13:00,21:00)，dt2 的 08-17 [13:00,21:00)。
-- E：两列再各后移一小时，到 [14:00,22:00)。主查询使用 >= / <。
-- 每个窗口覆盖 8×8=64 个小时组合分区。A→D 和 D→E 各复用 7×7=49 个，
-- 新增小时所在的一行一列共 8+8-1=15 个分区需要计算；重复查询应 64/64 命中。
--
-- 执行：先选一个测试数据库，在同一个连接里按节执行。
-- mysql -h <FE_HOST> -P <QUERY_PORT> -u <USER> -p <TEST_DB> \
--       --comments --verbose < query_cache_dual_datetime_rolling_manual_test.sql
-- 本脚本只重建 qc_list_dt1_dt2_rolling、qc_list_dt1_dt2_multi 两张测试表，
-- 测试结束保留表及数据。关闭连接即可结束所有会话设置。
--
-- 缓存观察：EXPLAIN 的 DIGEST 表示计划可缓存；实际命中必须看完整 Profile。
-- 每条目标 SELECT 后立即 SELECT LAST_QUERY_ID(); 保存 ID，再 SHOW QUERY PROFILE;
-- 如 Profile 未完整，等待刷新；FE HTTP /api/profile/text?query_id=<QUERY_ID> 可取原文。
-- 在 DetailProfile 的 CACHE_SOURCE 中按 CacheTabletId 去重统计 HitCache 1/0，
-- 不要将 MergedProfile 和原始实例重复计数。SHOW TABLETS 不含 PartitionId，
-- 可用 SHOW TABLETS FROM qc_list_dt1_dt2_rolling PARTITION(p13_13) 对照具体分区。
-- SQL Cache 和增量 Query Cache 已关闭；测试复用阶段不写数据，也不强制刷新缓存。
-- 命中预期要求缓存保留、数据版本不变、BE 未重启或迁移；只看耗时不能证明命中。
--
-- R 为第 1 节 CROSS JOIN numbers 的倍率，默认 "1"；需要放大可改为 "4"，
-- 得到 8,294,400 行。所有普通 SUM/COUNT 随 R 放大，时间范围及去重时间数不变。
-- 每小时组合行数为 3600*R，每个秒值出现 24*R 次；多 tuple 小表不随 R 放大。
-- 写入测试只加一行：SUM +1000000000、COUNT +1，不乘 R。
-- 开关 enable_query_cache 不会清空已存缓存；复现首次滚动须从建表重新执行。
-- 以前按天分区的 9/36、16/36 预期及性能报告不适用于本脚本。

